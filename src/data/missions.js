export const MISSION_BY_ID = MISSIONS.reduce((acc, mission) => {
  acc[mission.id] = mission;
  return acc;
}, {});

/** Missions that visited or study a given body id. */
export function missionsForBody(bodyId) {
  return MISSIONS.filter((mission) => mission.destinationIds.includes(bodyId));
}
